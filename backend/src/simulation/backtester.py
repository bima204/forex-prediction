"""
Event-Driven Backtesting Simulation Engine.
Accurately models spread, slippage, dynamic lot sizes, trailing stops, and equity drawdown.
"""
from typing import Dict, Any, List, Optional
import numpy as np
import pandas as pd
from datetime import datetime

from .position import TradePosition
from .risk_manager import RiskManager
from config.settings import DEFAULT_PAIRS


class Backtester:
    """
    Simulates high-fidelity autonomous trading execution over historical candlestick data.
    """

    def __init__(
        self,
        initial_capital: float = 10000.0,
        risk_manager: Optional[RiskManager] = None,
        use_trailing_stop: bool = True,
    ):
        self.initial_capital = initial_capital
        self.risk_manager = risk_manager or RiskManager()
        self.use_trailing_stop = use_trailing_stop

    def run_simulation(
        self,
        df: pd.DataFrame,
        signals: pd.DataFrame,
        symbol: str = "EURUSD",
        tp_mult: float = 2.0,
        sl_mult: float = 1.0,
    ) -> Dict[str, Any]:
        """
        Runs step-by-step bar simulation.
        
        Args:
            df: OHLCV DataFrame
            signals: DataFrame containing at least ['action', 'confidence', 'tp_price', 'sl_price']
                     or columns generated by model.
        """
        pair_info = DEFAULT_PAIRS.get(symbol.upper(), {})
        pip_value = pair_info.get("pip_value", 0.0001)

        balance = self.initial_capital
        open_positions: List[TradePosition] = []
        closed_positions: List[TradePosition] = []
        equity_records = []
        ticket_counter = 1

        timestamps = df.index
        opens = df["open"].values
        highs = df["high"].values
        lows = df["low"].values
        closes = df["close"].values

        for i in range(len(df)):
            current_time = timestamps[i]
            cur_open = opens[i]
            cur_high = highs[i]
            cur_low = lows[i]
            cur_close = closes[i]

            # 1. Manage Existing Open Positions
            surviving_positions = []
            for pos in open_positions:
                closed = False

                if pos.direction == "BUY":
                    # Check Stop Loss first (conservative)
                    if cur_low <= pos.stop_loss:
                        pos.close(pos.stop_loss, current_time, "CLOSED_SL", pip_value=pip_value)
                        balance += pos.pnl_cash
                        closed_positions.append(pos)
                        closed = True
                    # Check Take Profit
                    elif cur_high >= pos.take_profit:
                        pos.close(pos.take_profit, current_time, "CLOSED_TP", pip_value=pip_value)
                        balance += pos.pnl_cash
                        closed_positions.append(pos)
                        closed = True
                    # Trailing Stop Update
                    elif self.use_trailing_stop:
                        pos.update_trailing_stop(cur_close, pip_value=pip_value)

                elif pos.direction == "SELL":
                    # Check Stop Loss
                    if cur_high >= pos.stop_loss:
                        pos.close(pos.stop_loss, current_time, "CLOSED_SL", pip_value=pip_value)
                        balance += pos.pnl_cash
                        closed_positions.append(pos)
                        closed = True
                    # Check Take Profit
                    elif cur_low <= pos.take_profit:
                        pos.close(pos.take_profit, current_time, "CLOSED_TP", pip_value=pip_value)
                        balance += pos.pnl_cash
                        closed_positions.append(pos)
                        closed = True
                    # Trailing Stop Update
                    elif self.use_trailing_stop:
                        pos.update_trailing_stop(cur_close, pip_value=pip_value)

                if not closed:
                    surviving_positions.append(pos)

            open_positions = surviving_positions

            # 2. Check for New Signal Execution
            if i < len(signals):
                sig_row = signals.iloc[i]
                action = sig_row.get("action", "HOLD")

                if action in ["BUY", "SELL"]:
                    can_open, _ = self.risk_manager.can_open_new_trade(len(open_positions))
                    if can_open:
                        tp_target = float(sig_row["take_profit"])
                        sl_target = float(sig_row["stop_loss"])
                        sl_pips = abs(cur_close - sl_target) / pip_value

                        if sl_pips > 5.0:  # Valid minimum risk distance
                            lot_size = self.risk_manager.calculate_lot_size(
                                account_balance=balance,
                                sl_pips=sl_pips,
                                pip_value=pip_value,
                            )
                            # Apply execution friction (spread + slippage)
                            exec_price = self.risk_manager.apply_execution_costs(cur_close, action, pip_value=pip_value)

                            new_pos = TradePosition(
                                ticket_id=ticket_counter,
                                symbol=symbol,
                                direction=action,
                                lot_size=lot_size,
                                entry_price=exec_price,
                                entry_time=current_time,
                                stop_loss=sl_target,
                                take_profit=tp_target,
                            )
                            open_positions.append(new_pos)
                            ticket_counter += 1

            # 3. Calculate Unrealized Equity for this Bar
            unrealized_pnl = 0.0
            for pos in open_positions:
                if pos.direction == "BUY":
                    unrealized_pnl += (cur_close - pos.entry_price) * 100000.0 * pos.lot_size
                else:
                    unrealized_pnl += (pos.entry_price - cur_close) * 100000.0 * pos.lot_size

            equity = balance + unrealized_pnl
            equity_records.append({"time": current_time, "balance": balance, "equity": equity})

        # Compile Equity Curve
        equity_df = pd.DataFrame(equity_records).set_index("time")

        # Compile Performance Metrics
        report = self._calculate_metrics(equity_df, closed_positions)
        report["symbol"] = symbol
        report["closed_trades_count"] = len(closed_positions)
        report["open_trades_count"] = len(open_positions)
        report["equity_curve"] = equity_df
        report["trades_list"] = closed_positions

        return report

    def _calculate_metrics(self, equity_df: pd.DataFrame, trades: List[TradePosition]) -> Dict[str, Any]:
        """
        Computes financial summary metrics: Max Drawdown, Sharpe Ratio, Profit Factor, Win Rate.
        """
        if equity_df.empty:
            return {"status": "No data"}

        initial_cap = self.initial_capital
        final_equity = equity_df["equity"].iloc[-1]
        net_profit = final_equity - initial_cap
        net_profit_pct = (net_profit / initial_cap) * 100.0

        # Drawdown calculation
        equity_series = equity_df["equity"]
        peak = equity_series.cummax()
        drawdown = (equity_series - peak) / peak * 100.0
        max_drawdown_pct = abs(float(drawdown.min())) if not drawdown.empty else 0.0

        # Win Rate and Profit Factor from closed trades
        if trades:
            wins = [t.pnl_cash for t in trades if t.pnl_cash > 0]
            losses = [abs(t.pnl_cash) for t in trades if t.pnl_cash <= 0]

            win_count = len(wins)
            loss_count = len(losses)
            total_closed = len(trades)
            win_rate = (win_count / total_closed) * 100.0 if total_closed > 0 else 0.0

            gross_profit = sum(wins)
            gross_loss = sum(losses)
            profit_factor = gross_profit / (gross_loss + 1e-8) if gross_loss > 0 else gross_profit

            avg_win = gross_profit / win_count if win_count > 0 else 0.0
            avg_loss = gross_loss / loss_count if loss_count > 0 else 0.0
            rr_realized = avg_win / (avg_loss + 1e-8) if avg_loss > 0 else 0.0
        else:
            win_rate = 0.0
            profit_factor = 0.0
            avg_win = 0.0
            avg_loss = 0.0
            rr_realized = 0.0

        # Sharpe Ratio (Daily return approximation)
        returns = equity_series.pct_change().dropna()
        if len(returns) > 1 and returns.std() > 0:
            sharpe_ratio = float((returns.mean() / returns.std()) * np.sqrt(252 * 24))  # 1h candles
        else:
            sharpe_ratio = 0.0

        return {
            "initial_capital": initial_cap,
            "final_equity": round(final_equity, 2),
            "net_profit": round(net_profit, 2),
            "net_profit_pct": round(net_profit_pct, 2),
            "win_rate": round(win_rate, 2),
            "profit_factor": round(profit_factor, 2),
            "risk_reward_realized": round(rr_realized, 2),
            "max_drawdown_pct": round(max_drawdown_pct, 2),
            "sharpe_ratio": round(sharpe_ratio, 2),
        }
